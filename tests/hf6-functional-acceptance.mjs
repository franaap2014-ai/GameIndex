import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import os from 'node:os';import path from 'node:path';
const tmp=mkdtempSync(path.join(os.tmpdir(),'gi-hf6-functional-'));
process.env.GAMEINDEX_DB=path.join(tmp,'db.sqlite');process.env.GAMEINDEX_DATA_DIR=tmp;process.env.GAMEINDEX_TARGET_SCHEMA='28';
const c=await import('../src/database/connection.mjs');c.migrateDatabase();
const repo=await import('../src/database/repositories/game-repository.mjs');
for(let i=1;i<=40;i++)repo.upsertGame({name:`HF6 Game ${String(i).padStart(2,'0')}`,slug:`hf6-game-${i}`,status:'PUBLISHED',genres:['Test'],platforms:['PC']});
const first=repo.listGamesPage({includeDrafts:false,limit:24,offset:0});
const second=repo.listGamesPage({includeDrafts:false,limit:24,offset:24});
assert.ok(first.total>=40);assert.equal(first.items.length,24);assert.ok(second.items.length>=16);
const music=await import('../src/music/youtube-music-service.mjs');
assert.equal(music.parseYouTubeVideoId('https://youtu.be/dQw4w9WgXcQ'),'dQw4w9WgXcQ');
assert.equal(music.parseYouTubeVideoId('javascript:alert(1)'),null);
const home=music.setHomeMusic({youtubeUrl:'https://www.youtube.com/watch?v=dQw4w9WgXcQ',userId:'hf6-test'});
assert.equal(home.youtubeVideoId,'dQw4w9WgXcQ');assert.match(home.youtubeUrl,/youtube\.com\/watch\?v=dQw4w9WgXcQ/);
const game=first.items[0],gp=music.setGameMusic({gameId:game.id,youtubeUrl:'https://www.youtube.com/shorts/dQw4w9WgXcQ'});assert.equal(gp.gameId,String(game.id));
music.removeHomeMusic();music.removeGameMusic(game.id);assert.equal(music.homeMusicProfile(),null);assert.equal(music.gameMusicProfile(game.id),null);
try{c.db.close()}catch{}rmSync(tmp,{recursive:true,force:true});
console.log('HF6 functional acceptance: PASS — SQL pagination 24 + YouTube music persistence/validation.');
